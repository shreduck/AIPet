"""Deterministic Cowork plugin and CLI marketplace generation."""
import os
import sys
import zipfile
from . import commands as hook_commands
from . import deployment as hook_deployment
from . import locations as hook_locations
from . import protocol as hook_protocol
from . import settings as hook_settings

IS_MAC = sys.platform == "darwin"


PLUGIN_NAME = "pet-hooks"  # names starting with "claude-" are reserved for Anthropic's own plugins


PLUGIN_MARKET = "desktop-pet-local"


PLUGIN_VERSION = "1.0.0"


COWORK_ZIP = "aipet-cowork-plugin.zip"


_ZIP_TIME = (2026, 1, 1, 0, 0, 0)  # fixed timestamps -> identical bytes for identical content


def plugin_hooks(command):
    """hooks.json for the plugin: the same events, matchers and timeouts as the settings.json install."""
    hooks = {}
    for event, matcher in hook_protocol.HOOK_EVENTS:
        entry = {"hooks": [{"type": "command", "command": command,
                            **({"timeout": hook_protocol.HOOK_TIMEOUTS[event]} if event in hook_protocol.HOOK_TIMEOUTS else {})}]}
        if matcher:
            entry = {"matcher": matcher, **entry}
        hooks[event] = [entry]
    return {"hooks": hooks}


def plugin_files(command):
    """{relative path: bytes} of the plugin's root folder."""
    readme = (
        "AIPet hooks for the Claude desktop app (Cowork) and the Claude Code CLI.\n\n"
        "Generated by AIPet for this computer: the hooks call the AIPet hook installed in\n"
        f"{hook_locations.PET_DIR}. Regenerate it from AIPet (Claude Code hooks > Cowork) if that moves.\n\n"
        "Don't use it in the same place as AIPet's settings.json hooks, or every event reaches the pet twice.\n")
    return {
        ".claude-plugin/plugin.json": hook_settings.dump({
            "name": PLUGIN_NAME, "version": PLUGIN_VERSION,
            "description": "Shows your Claude sessions on the AIPet desktop companion.",
            "author": {"name": "AIPet"}}).encode(),
        "hooks/hooks.json": hook_settings.dump(plugin_hooks(command)).encode(),
        "README.md": readme.encode(),
    }


def _write_if_changed(path, data):
    try:
        with open(path, "rb") as f:
            if f.read() == data:
                return
    except OSError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".new"
    with open(tmp, "wb") as f:
        f.write(data)
    os.replace(tmp, path)


def _zip_bytes(files):
    import io
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for rel in sorted(files):
            info = zipfile.ZipInfo(rel, _ZIP_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, files[rel])
    return buf.getvalue()


def build_plugin():
    """Deploy the hook, then write the Cowork zip to ~/.aipet on macOS, or next to the Windows exe
    (falling back to ~/.aipet if that folder is read-only), plus a local marketplace for the CLI.
    Returns {"zip": path, "market": dir, "command": hook command}.
    Files are only rewritten when their content changes."""
    hook_deployment.deploy_files()
    command = hook_commands.local_hook_command()
    files = plugin_files(command)
    data = _zip_bytes(files)
    zip_path, err = None, None
    # A writable macOS app bundle is still sealed by its code signature. Adding
    # generated files beside its executable invalidates that signature.
    zip_dirs = (hook_locations.PET_DIR,) if IS_MAC else (hook_locations.app_dir(), hook_locations.PET_DIR)
    for d in zip_dirs:
        try:
            _write_if_changed(os.path.join(d, COWORK_ZIP), data)
            zip_path = os.path.join(d, COWORK_ZIP)
            break
        except OSError as e:
            err = e
    if not zip_path:
        raise RuntimeError(f"Couldn't write {COWORK_ZIP}: {err}")
    market = {".claude-plugin/marketplace.json": hook_settings.dump({
        "name": PLUGIN_MARKET, "owner": {"name": "AIPet"},
        "metadata": {"description": "Local marketplace generated by AIPet for this computer."},
        "plugins": [{"name": PLUGIN_NAME, "source": "./" + PLUGIN_NAME,
                     "description": "Shows your Claude sessions on the AIPet desktop companion."}]}).encode()}
    market.update({f"{PLUGIN_NAME}/{rel}": b for rel, b in files.items()})
    for rel, b in market.items():
        _write_if_changed(os.path.join(hook_locations.PLUGIN_MARKET_DIR, *rel.split("/")), b)
    return {"zip": zip_path, "market": hook_locations.PLUGIN_MARKET_DIR, "command": command}


def cli_plugin_commands(market_dir=hook_locations.PLUGIN_MARKET_DIR):
    return [f'claude plugin marketplace add "{market_dir}"',
            f"claude plugin install {PLUGIN_NAME}@{PLUGIN_MARKET}"]
